from abc import ABC, abstractmethod

import pandas_ta as ta

class BaseStrategy(ABC):
    def __init__(self, config=None):
        self.name = self.__class__.__name__
        self.config = config or {}

    @abstractmethod
    def generate_signal(self, df):
        pass

class ScalpEmaRsi(BaseStrategy):
    def generate_signal(self, df):
        # 0. Safety Check
        if df.empty or len(df) < 50: 
            return None
            
        params = self.config.get("params", {})
        ema_fast_len = params.get("ema_fast", 9)
        ema_slow_len = params.get("ema_slow", 21)
        rsi_len = params.get("rsi_period", 14)
        
        # 1. Calculate Indicators
        # Using pandas_ta directly on the dataframe
        df.ta.ema(length=ema_fast_len, append=True)
        df.ta.ema(length=ema_slow_len, append=True)
        df.ta.ema(length=ema_slow_len, append=True)
        df.ta.rsi(length=rsi_len, append=True)
        df.ta.atr(length=14, append=True) # Calculate ATR for Stops
        
        # Columns names generated by pandas_ta are like 'EMA_9', 'EMA_21', 'RSI_14'
        fast_col = f"EMA_{ema_fast_len}"
        slow_col = f"EMA_{ema_slow_len}"
        rsi_col = f"RSI_{rsi_len}"
        atr_col = "ATRr_14"
        
        if fast_col not in df.columns or atr_col not in df.columns: return None

        # 2. Get latest values
        current_fast = df[fast_col].iloc[-1]
        prev_fast = df[fast_col].iloc[-2]
        current_slow = df[slow_col].iloc[-1]
        prev_slow = df[slow_col].iloc[-2]
        current_rsi = df[rsi_col].iloc[-1]
        close = df['close'].iloc[-1]
        atr = df[atr_col].iloc[-1]
        
        # 3. Logic: Crossover
        # BUY: Fast crosses ABOVE Slow
        if prev_fast <= prev_slow and current_fast > current_slow:
            if current_rsi < params.get("rsi_overbought", 70): # Filter
                return {
                    "signal": "BUY",
                    "sl": close - (1.5 * atr),
                    "tp": close + (3.0 * atr),
                    "comment": "EMA Crossover + RSI"
                }
                
        # SELL: Fast crosses BELOW Slow
        if prev_fast >= prev_slow and current_fast < current_slow:
            if current_rsi > params.get("rsi_oversold", 30):
                return {
                    "signal": "SELL",
                    "sl": close + (1.5 * atr),
                    "tp": close - (3.0 * atr),
                    "comment": "EMA Crossover + RSI"
                }
        return None

