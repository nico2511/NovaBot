class SwingTrendPullback(BaseStrategy):
    def generate_signal(self, df):
        if df.empty or len(df) < 200: return None
        
        params = self.config.get("params", {})
        ema_trend_len = params.get("ema_trend", 200)
        ema_fast_len = params.get("ema_pullback_fast", 20)
        ema_slow_len = params.get("ema_pullback_slow", 50)
        
        # 1. Indicators
        df.ta.ema(length=ema_trend_len, append=True)
        df.ta.ema(length=ema_fast_len, append=True)
        df.ta.ema(length=ema_slow_len, append=True)
        df.ta.rsi(length=14, append=True)
        df.ta.atr(length=14, append=True)
        
        trend_col = f"EMA_{ema_trend_len}"
        fast_col = f"EMA_{ema_fast_len}"
        slow_col = f"EMA_{ema_slow_len}"
        rsi_col = "RSI_14"
        atr_col = "ATRr_14"
        
        if trend_col not in df.columns: return None
        
        close = df['close'].iloc[-1]
        low = df['low'].iloc[-1]
        high = df['high'].iloc[-1]
        trend = df[trend_col].iloc[-1]
        ema_fast = df[fast_col].iloc[-1]
        ema_slow = df[slow_col].iloc[-1]
        rsi = df[rsi_col].iloc[-1]
        atr = df[atr_col].iloc[-1] if atr_col in df.columns else (close * 0.01)
        
        # LONG: Overall Trend Bullish (Price > EMA200)
        if close > trend:
            if low <= ema_fast and rsi > params.get("rsi_min_long", 40):
                 return {
                    "signal": "BUY",
                    "sl": close - (2.0 * atr),
                    "tp": close + (5.0 * atr),
                    "comment": "Trend Pullback"
                }

        # SHORT: Overall Trend Bearish (Price < EMA200)
        if close < trend:
            if high >= ema_fast and rsi < params.get("rsi_max_short", 60):
                return {
                    "signal": "SELL",
                    "sl": close + (2.0 * atr),
                    "tp": close - (5.0 * atr),
                    "comment": "Trend Pullback"
                }
        return None

class DayTradingORB(BaseStrategy):
    def generate_signal(self, df):
        # Requires intraday data with timestamps
        if df.empty: return None
        
        # Calculate VWAP
        df.ta.vwap(append=True) # VWAP requires volume, high, low, close
        df.ta.atr(length=14, append=True)
        if 'VWAP_D' not in df.columns: return None
        
        vwap = df['VWAP_D'].iloc[-1]
        close = df['close'].iloc[-1]
        
        # Simplified ORB Logic (Session agnostic for now, just takes last N candles as "Range" if implied)
        # Real ORB needs specific time of day. 
        # Assuming we run this live during the session.
        # Check breakout of previous High/Low?
        
        # For this iteration, we implemented a simple VWAP Trend Follow
        if close > vwap:
            atr = df['ATRr_14'].iloc[-1] if 'ATRr_14' in df.columns else (close * 0.01)
            return {
                "signal": "BUY",
                "sl": close - atr,
                "tp": close + (2 * atr),
                "comment": "VWAP Trend"
            }
        elif close < vwap:
            atr = df['ATRr_14'].iloc[-1] if 'ATRr_14' in df.columns else (close * 0.01)
            return {
                "signal": "SELL",
                "sl": close + atr,
                "tp": close - (2 * atr),
                "comment": "VWAP Trend"
            }
            
        return None

